#!/usr/bin/env node
/* eslint-disable no-console */
// Regenerate pkg/ai-templating/install/manifests.ts from the YAML sources, so the extension can
// embed and auto-install its cluster dependencies (see pkg/ai-templating/install/ensure.ts).
//
//   node scripts/gen-manifests.mjs
//
// Sources (ConfigMap storage — no CRDs):
//   pkg/ai-templating/agents/*.aiagentconfig.yaml            -> AGENT_CRS
//   pkg/ai-templating/examples/seed-configmaps.yaml          -> SEED_CONFIGMAPS
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import yaml from 'js-yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(root, 'pkg/ai-templating');

const loadAll = (p) => yaml.loadAll(fs.readFileSync(p, 'utf8')).filter(Boolean);
const load = (p) => yaml.load(fs.readFileSync(p, 'utf8'));

const agents = fs.readdirSync(path.join(base, 'agents'))
  .filter((f) => f.endsWith('.yaml'))
  .map((f) => load(path.join(base, 'agents', f)));

// Seed the config singleton + a default Home ConfigMap so a fresh install shows a working Home.
const seed = loadAll(path.join(base, 'examples/seed-configmaps.yaml'));

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/gen-manifests.mjs — do not edit by hand.
// Embedded manifests the extension ensures on install (see install/ensure.ts).

export const AGENT_CRS: any[] = ${ JSON.stringify(agents, null, 2) };

export const SEED_CONFIGMAPS: any[] = ${ JSON.stringify(seed, null, 2) };
`;

fs.writeFileSync(path.join(base, 'install/manifests.ts'), out);
console.log('wrote install/manifests.ts', { agents: agents.length, seed: seed.length });
